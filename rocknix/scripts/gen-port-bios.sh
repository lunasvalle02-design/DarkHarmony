#!/bin/sh
# Regenerates the port BIOS (rocknix/bios/port_bios.s) outputs committed in the
# repo: port_bios.bin (the 16 KiB image the runtime maps at 0x00000000),
# port_bios.toml (every label as a function entry) and generated/ (the
# gba_recompile --bios output linked into hod.aarch64).
# Needs arm-none-eabi binutils and a host compiler, e.g. the x86 test image:
#   docker run --rm -v <repo>:/work hod-x86-test sh rocknix/scripts/gen-port-bios.sh
set -eu
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
B="$ROOT/rocknix/bios"
T="$(mktemp -d)"
trap 'rm -rf "$T"' EXIT

arm-none-eabi-as -mcpu=arm7tdmi -o "$T/bios.o" "$B/port_bios.s"
arm-none-eabi-objcopy -O binary "$T/bios.o" "$T/bios.raw"
size=$(wc -c < "$T/bios.raw")
cp "$T/bios.raw" "$B/port_bios.bin"
head -c $((16384 - size)) /dev/zero >> "$B/port_bios.bin"

{
  echo "# Generated by rocknix/scripts/gen-port-bios.sh from port_bios.s — do not edit."
  echo "[program]"
  echo "name         = \"HoD port BIOS\""
  echo "id           = \"hod_port_bios\""
  echo "load_address = 0x00000000"
  echo "size         = 0x00004000"
  echo "entry_pc     = 0x00000000"
  echo "static_resume_all = true"
  echo
  echo "[identity]"
  echo "sha1 = \"$(sha1sum "$B/port_bios.bin" | cut -d" " -f1)\""
  echo "md5  = \"$(md5sum "$B/port_bios.bin" | cut -d" " -f1)\""
  printf '\n[[extra_func]]\naddr = 0x00000000\nmode = "arm"\nname = "bios_reset_vector"\n'
  printf '\n[[extra_func]]\naddr = 0x00000008\nmode = "arm"\nname = "bios_swi_vector"\n'
  printf '\n[[extra_func]]\naddr = 0x00000018\nmode = "arm"\nname = "bios_irq_vector"\n'
  arm-none-eabi-nm -n "$T/bios.o" | awk '$2 == "t" || $2 == "T" { print $1, $3 }' |
    while read -r addr name; do
      case "$name" in \$*|.L*) continue ;; esac
      printf '\n[[extra_func]]\naddr = 0x%s\nmode = "arm"\nname = "pbios_%s"\n' "$addr" "$name"
    done
} > "$B/port_bios.toml"

if [ ! -x "$ROOT/build/host-tools/gba_recompile" ]; then
  cmake -S "$ROOT/external/gbarecomp" -B "$ROOT/build/host-tools" -G Ninja \
    -DCMAKE_BUILD_TYPE=Release -DGBARECOMP_TOMLPP_INCLUDE_DIR="$ROOT/external/tomlplusplus" >/dev/null
  cmake --build "$ROOT/build/host-tools" --target gba_recompile >/dev/null
fi
rm -rf "$B/generated"
mkdir -p "$B/generated"
"$ROOT/build/host-tools/gba_recompile" --bios "$B/port_bios.bin" --config "$B/port_bios.toml" \
  --out "$B/generated"
sha1sum "$B/port_bios.bin"
